create table if not exists public.plagia_orders (
  id bigint generated by default as identity primary key,
  report_id text not null unique,
  name text not null,
  email text not null,
  amount numeric(10,2) not null default 20.00,
  status text not null default 'pending'
    check (status in ('pending','review','paid','cancelled')),
  payment_reference text,
  report_hash text,
  created_at timestamptz not null default now(),
  paid_at timestamptz
);

create index if not exists plagia_orders_email_idx
  on public.plagia_orders (email);

create index if not exists plagia_orders_status_idx
  on public.plagia_orders (status);

create unique index if not exists plagia_orders_active_payment_reference_idx
  on public.plagia_orders (lower(payment_reference))
  where status in ('review', 'paid') and payment_reference is not null;

alter table public.plagia_orders enable row level security;

-- O aplicativo usa a service role apenas no servidor.
-- Não crie políticas públicas de leitura ou escrita nesta tabela.

insert into storage.buckets (id, name, public)
values ('plagia-reports', 'plagia-reports', false)
on conflict (id) do update set public = false;
